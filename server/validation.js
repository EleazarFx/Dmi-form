'use strict';

const path = require('node:path');

const PROGRAMMES = [
  'Business Administration',
  'Computer Science',
  'Computer Engineering',
  'Education in Arts',
  'Education in Science',
  'Social Work',
];

const SPECIAL_NEEDS = [
  'none',
  'learning-difficulty',
  'hearing',
  'personal-care',
  'unseen',
  'visual',
  'mobility',
  'mental-health',
  'other',
];

const CHECK_ITEMS = [
  ['check-certificates', 'copies of your certificates and transcripts'],
  ['check-funding', 'your source of funding'],
  ['check-payment', 'proof of payment of the application fee'],
];

const ALLOWED = {
  programmeLevel: new Set(['diploma', 'bachelor-degree']),
  title: new Set(['mr', 'ms']),
  gender: new Set(['male', 'female']),
  maritalStatus: new Set(['married', 'single']),
  programme: new Set(PROGRAMMES),
  mode: new Set(['face-to-face', 'blended', 'online']),
  campus: new Set(['MH', 'LW', 'BT']),
  qualificationType: new Set(['msce', 'o-level', 'a-level', 'other']),
  specialNeed: new Set(SPECIAL_NEEDS),
};

const CHOICE_LABELS = { first: 'First Choice', second: 'Second Choice', third: 'Third Choice' };
const QUALIFICATION_DETAILS = ['qualification', 'certificate', 'school', 'centre', 'candidate', 'country'];
const IMAGE_MIME_TYPES = new Set(['image/jpeg', 'image/png', 'image/webp']);
const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const MAX_FIELD_LENGTH = 2000;

/** Return the first (trimmed) value of a field. */
function field(body, name) {
  const value = Array.isArray(body[name]) ? body[name][0] : body[name];
  return typeof value === 'string' ? value.trim() : '';
}

/** Return all (trimmed) values of a possibly repeated field. */
function list(body, name) {
  if (body[name] == null) return [];
  const values = Array.isArray(body[name]) ? body[name] : [body[name]];
  return values.map((value) => String(value).trim()).filter(Boolean);
}

function isIsoDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

function calculatedAge(dateOfBirth) {
  const born = new Date(`${dateOfBirth}T00:00:00Z`);
  const now = new Date();
  let age = now.getUTCFullYear() - born.getUTCFullYear();
  if (
    now.getUTCMonth() < born.getUTCMonth() ||
    (now.getUTCMonth() === born.getUTCMonth() && now.getUTCDate() < born.getUTCDate())
  ) {
    age -= 1;
  }
  return age;
}

/**
 * Validate every submitted form field.
 * Returns { errors: { fieldName: message }, value: normalised data for the database }.
 */
function validateApplication(body = {}, file) {
  const errors = {};
  const value = {};
  const today = new Date().toISOString().slice(0, 10);
  const currentYear = new Date().getUTCFullYear();

  const add = (name, message) => {
    if (!errors[name]) errors[name] = message;
  };

  const required = (name, label, maxLength = 120) => {
    const v = field(body, name);
    if (!v) add(name, `${label} is required.`);
    else if (v.length > maxLength) add(name, `${label} must be at most ${maxLength} characters.`);
    return v;
  };

  const optional = (name, maxLength = MAX_FIELD_LENGTH) => {
    const v = field(body, name);
    if (v.length > maxLength) add(name, `${name} must be at most ${maxLength} characters.`);
    return v || null;
  };

  // --- Application details -------------------------------------------------
  const programmeLevel = field(body, 'programme-level');
  if (!programmeLevel) add('programme-level', 'Choose Diploma or Bachelor Degree.');
  else if (!ALLOWED.programmeLevel.has(programmeLevel)) add('programme-level', 'Choose a valid programme level.');
  value.programmeLevel = programmeLevel;

  // The application number is generated by the server; never trust the client.
  value.applicationNumber = null;

  // --- A. Personal details -------------------------------------------------
  const title = field(body, 'title');
  if (!title) add('title', 'Choose a title.');
  else if (!ALLOWED.title.has(title)) add('title', 'Choose a valid title.');

  const gender = field(body, 'gender');
  if (!gender) add('gender', 'Choose a gender.');
  else if (!ALLOWED.gender.has(gender)) add('gender', 'Choose a valid gender.');

  const maritalStatus = field(body, 'marital-status');
  if (!maritalStatus) add('marital-status', 'Choose a marital status.');
  else if (!ALLOWED.maritalStatus.has(maritalStatus)) add('marital-status', 'Choose a valid marital status.');

  const dateOfBirth = required('date-of-birth', 'Date of birth', 10);
  if (dateOfBirth && !isIsoDate(dateOfBirth)) add('date-of-birth', 'Enter a valid date of birth.');
  else if (dateOfBirth && dateOfBirth > today) add('date-of-birth', 'Date of birth cannot be in the future.');
  else if (dateOfBirth && dateOfBirth.slice(0, 4) < '1900') add('date-of-birth', 'Date of birth must be after 1900.');

  const ageValue = required('age', 'Age', 3);
  const age = Number(ageValue);
  if (ageValue && (!/^\d+$/.test(ageValue) || age < 0 || age > 120)) {
    add('age', 'Enter an age between 0 and 120.');
  } else if (ageValue && isIsoDate(dateOfBirth) && Math.abs(calculatedAge(dateOfBirth) - age) > 1) {
    add('age', 'Age must match the date of birth.');
  }

  value.applicant = {
    title,
    surname: required('surname', 'Surname'),
    firstName: required('first-name', 'First name'),
    initial: optional('initial', 5),
    gender,
    dateOfBirth,
    age: ageValue,
    maritalStatus,
    nationality: required('nationality', 'Nationality'),
    religion: optional('religion'),
    homeDistrict: required('home-district', 'Home district'),
    traditionalAuthority: optional('traditional-authority'),
    village: optional('village'),
    tribe: optional('tribe'),
    passportNrcNumber: required('passport-nrc-number', 'Passport/NRC number', 40),
  };

  // --- B. Next of kin ------------------------------------------------------
  const kinEmail = field(body, 'kin-email');
  if (kinEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(kinEmail)) {
    add('kin-email', 'Enter a valid email address (e.g. name@example.com).');
  }

  const kinMobile = required('kin-mobile', 'Next of kin mobile number', 20);
  const mobileDigits = kinMobile.replace(/\D/g, '');
  if (kinMobile && (!/^\+?[0-9][0-9\s()-]*$/.test(kinMobile) || mobileDigits.length < 7 || mobileDigits.length > 15)) {
    add('kin-mobile', 'Enter a valid phone number (7-15 digits, optional + country code).');
  }

  value.kin = {
    title: optional('kin-title', 40),
    surname: required('kin-surname', 'Next of kin surname'),
    firstName: required('kin-first-name', 'Next of kin first name'),
    initial: optional('kin-initial', 5),
    address: optional('kin-address'),
    email: kinEmail || null,
    mobile: kinMobile,
    occupation: optional('kin-occupation'),
    organization: optional('kin-organization'),
    relationship: required('kin-relationship', 'Relationship with next of kin'),
  };

  // --- C. Programme choices ------------------------------------------------
  const choices = [];
  const selectedProgrammes = new Set();
  for (const key of ['first', 'second', 'third']) {
    const programme = field(body, `${key}-programme`);
    const mode = field(body, `${key}-mode`);
    const campus = field(body, `${key}-campus`);
    const label = CHOICE_LABELS[key];
    const hasAny = Boolean(programme || mode || campus);

    if (key === 'first' && !hasAny) {
      add(`${key}-programme`, 'Select a programme for your first choice.');
    }

    if (hasAny) {
      if (!programme) add(`${key}-programme`, `Select a programme for ${label.toLowerCase()}.`);
      else if (!ALLOWED.programme.has(programme)) add(`${key}-programme`, 'Select a programme from the list.');
      else if (selectedProgrammes.has(programme)) add(`${key}-programme`, 'This programme is already one of your choices.');
      else selectedProgrammes.add(programme);

      if (!mode || !ALLOWED.mode.has(mode)) add(`${key}-mode`, `Select a mode of learning for ${label.toLowerCase()}.`);
      if (!campus || !ALLOWED.campus.has(campus)) add(`${key}-campus`, `Select a campus for ${label.toLowerCase()}.`);
    }

    choices.push({
      choiceNumber: key === 'first' ? 1 : key === 'second' ? 2 : 3,
      programme: programme || null,
      mode: mode || null,
      campus: campus || null,
    });
  }
  value.choices = choices;

  // --- E. Previous academic record ----------------------------------------
  const previousAnswer = field(body, 'previous-public-university').toLowerCase();
  if (!previousAnswer || !['yes', 'no'].includes(previousAnswer)) {
    add('previous-public-university', 'Select Yes or No.');
  }

  const previousWhen = field(body, 'previous-when');
  if (previousAnswer === 'yes') {
    if (!previousWhen) add('previous-when', 'Enter when you were registered.');
    else if (!isIsoDate(previousWhen)) add('previous-when', 'Enter a valid date.');
    required('previous-programme', 'Previous programme');
    required('previous-institution', 'Previous institution');
    required('reason-for-leaving', 'Reason for leaving', MAX_FIELD_LENGTH);
  }

  value.previousEducation = {
    attendedPublicUniversity: previousAnswer || null,
    whenDate: previousWhen || null,
    programme: optional('previous-programme'),
    institution: optional('previous-institution'),
    reasonForLeaving: optional('reason-for-leaving', MAX_FIELD_LENGTH),
  };

  // --- F. Academic record --------------------------------------------------
  const qualificationType = field(body, 'qualification-type');
  if (!qualificationType) add('qualification-type', 'Choose a qualification type.');
  else if (!ALLOWED.qualificationType.has(qualificationType)) add('qualification-type', 'Choose a valid qualification type.');

  const qualificationOther = field(body, 'qualification-other');
  if (qualificationType === 'other' && !qualificationOther) {
    add('qualification-other', 'Specify your qualification.');
  }
  value.qualificationType = qualificationType;
  value.qualificationOther = qualificationOther || null;

  const qualifications = [];
  const subjects = [];

  for (const level of ['msce', 'alevel']) {
    for (let attempt = 1; attempt <= 3; attempt += 1) {
      const get = (name) => field(body, `${level}-${name}-${attempt}`);
      const attemptSubjects = Array.from({ length: 10 }, (_, index) => get(`subject-${index + 1}`));
      const year = get('year');
      // Subjects are often listed across the three attempt columns rather than
      // repeated for each attempt, so subjects alone do not count as an attempt.
      const hasMetadata = Boolean(year) || QUALIFICATION_DETAILS.some((name) => get(name));
      const hasAnyData = hasMetadata || ['from', 'to'].some((name) => get(name)) || attemptSubjects.some(Boolean);
      if (!hasAnyData) continue;

      // An attempt with no qualification details is simply stored as-is; only
      // attempts that actually claim an exam result need complete details.
      if (hasMetadata) {
        if (!year) add(`${level}-year-${attempt}`, `Year for attempt ${attempt} is required.`);
        else if (!/^\d{4}$/.test(year) || Number(year) < 1900 || Number(year) > currentYear + 1) {
          add(`${level}-year-${attempt}`, 'Enter a valid examination year.');
        }

        for (const detail of QUALIFICATION_DETAILS) {
          if (!get(detail)) {
            add(`${level}-${detail}-${attempt}`, `${detail.charAt(0).toUpperCase() + detail.slice(1)} for attempt ${attempt} is required.`);
          }
        }
      }

      qualifications.push({
        level,
        attempt,
        year: year || null,
        qualification: get('qualification') || null,
        certificateNumber: get('certificate') || null,
        school: get('school') || null,
        centreNumber: get('centre') || null,
        candidateNumber: get('candidate') || null,
        fromPeriod: get('from') || null,
        toPeriod: get('to') || null,
        country: get('country') || null,
      });

      attemptSubjects.forEach((subject, index) => {
        if (subject) subjects.push({ level, attempt, position: index + 1, subject });
      });
    }
  }

  const completeFields = ['year', 'qualification', 'certificateNumber', 'school', 'centreNumber', 'candidateNumber', 'country'];
  const requiredLevel = qualificationType === 'a-level' ? 'alevel' : qualificationType === 'msce' || qualificationType === 'o-level' ? 'msce' : null;
  const alreadyHasFieldError = Object.keys(errors).some((key) => key.startsWith(`${requiredLevel}-`));
  if (requiredLevel && !qualifications.some((item) => item.level === requiredLevel && completeFields.every((name) => Boolean(item[name]))) && !alreadyHasFieldError) {
    add(`${requiredLevel}-year-1`, 'Enter the complete details of at least one examination attempt.');
  }

  value.qualifications = qualifications;
  value.subjects = subjects;

  // --- G. Financial support ------------------------------------------------
  value.paymentPlan = required('payment-plan', 'Payment plan');
  value.sponsor = required('sponsor', 'Sponsor');

  // --- H. Special needs ----------------------------------------------------
  const specialNeeds = list(body, 'special-needs');
  for (const need of specialNeeds) {
    if (!ALLOWED.specialNeed.has(need)) add('special-needs', 'Select a valid special needs option.');
  }
  if (specialNeeds.includes('none') && specialNeeds.length > 1) {
    add('special-needs', '"No Disability" cannot be combined with other options.');
  }

  const additionalSupport = field(body, 'additional-support');
  if (specialNeeds.includes('other') && !additionalSupport) {
    add('additional-support', 'Describe the additional support you need.');
  }
  value.specialNeeds = specialNeeds;
  value.additionalSupport = additionalSupport || null;

  // --- Declaration and checklist ------------------------------------------
  value.declarationName = required('declaration-name', 'Declaration name');
  value.signature = required('signature', 'Signature');
  const declarationDate = required('declaration-date', 'Declaration date', 10);
  if (declarationDate && !isIsoDate(declarationDate)) add('declaration-date', 'Enter a valid declaration date.');
  else if (declarationDate && declarationDate > today) add('declaration-date', 'Declaration date cannot be in the future.');
  value.declarationDate = declarationDate;

  value.checklist = CHECK_ITEMS.map(([name]) => name);
  for (const [name, label] of CHECK_ITEMS) {
    if (!list(body, name).length) add(name, `Confirm that you have attached ${label}.`);
  }

  // --- Passport photo ------------------------------------------------------
  if (!file) {
    add('passport-photo', 'Attach a recent passport-size photo.');
  } else {
    const extension = path.extname(file.originalname || '').toLowerCase();
    if (!IMAGE_MIME_TYPES.has(file.mimetype) || !IMAGE_EXTENSIONS.has(extension)) {
      add('passport-photo', 'The photo must be a JPG, PNG or WebP image.');
    }
  }

  return { errors, value };
}

module.exports = { validateApplication };
